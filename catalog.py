def get_catalog():
    """Вернуть весь каталог"""
    return CATALOG

def get_category(cat_id):
    """Вернуть категорию по ID"""
    return CATALOG.get(cat_id)

def get_categories_by_tag(tag):
    """Найти категории по тегу"""
    result = {}
    for cat_id, cat_data in CATALOG.items():
        if tag in cat_data.get('tags', []):
            result[cat_id] = cat_data
    return result

def get_categories_by_price(min_price, max_price):
    """Найти категории по цене"""
    result = {}
    for cat_id, cat_data in CATALOG.items():
        if min_price <= cat_data['price'] <= max_price:
            result[cat_id] = cat_data
    return result

def get_popular_categories(limit=10):
    """Самые популярные категории"""
    sorted_cats = sorted(CATALOG.items(), key=lambda x: x[1]['popularity'], reverse=True)
    return dict(sorted_cats[:limit])

def format_category_text(cat_id, cat_data):
    """Форматировать текст категории"""
    text = f"📁 *{cat_data['name']}*\n"
    text += f"⭐ Рейтинг: {cat_data['rating']} (просмотров: {cat_data['popularity']:,})\n"
    text += f"📝 {cat_data['desc']}\n\n"
    text += "📋 *Содержимое:*\n"
    for item in cat_data['items']:
        text += f"• {item}\n"
    text += f"\n📊 Файлов: {cat_data.get('files', '?')} шт"
    text += f" ({cat_data.get('size', '?')})\n"
    text += f"🏷️ Теги: {', '.join(cat_data.get('tags', []))}\n"
    text += f"\n💰 *Цена:* {cat_data['price']} USDT\n"
    text += f"\n🆔 *ID:* `{cat_id}`"
    return text

